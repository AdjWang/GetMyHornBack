class BossLevel {
  constructor() {
    this._boss = levelObjInsts[0];
    this._bossSlots = [
      levelObjInsts[1].pos,
      levelObjInsts[2].pos,
      levelObjInsts[3].pos,
      levelObjInsts[4].pos,
      levelObjInsts[5].pos,
      levelObjInsts[6].pos,
    ];
    this._tntSlots = [
      ...this._bossSlots.slice(0, 3).map(pos => pos.add(vec2(-1, 0))),
      ...this._bossSlots.slice(3, 6).map(pos => pos.add(vec2(1, 0))),
    ];
    this._bossMoveTimer = new Timer;
    this._bossFireTimer = new Timer;
    this._boss.setBossSlot(this._bossSlots[0]);
  }

  start() {
    this._bossMoveTimer.unset();
    this._bossFireTimer.set(0.01);
  }

  update() {
    this._boss.setFaceDir(this._boss.pos.x < cameraPos.x ? 1 : 0);
    if (this._bossMoveTimer.isSet() && this._bossMoveTimer.elapsed()) {
      this._bossMoveTimer.unset();
      // Start to fire. Set timer including fire and cd.
      this._bossFireTimer.set(2.5);
      this._boss.fire(/*laserCount*/ 6, /*chargeTime*/ 1.5);
    }
    if (this._bossFireTimer.isSet() && this._bossFireTimer.elapsed()) {
      this._bossFireTimer.unset();
      // Start to move. Set timer including move and aim.
      this._bossMoveTimer.set(1.5);
      const targetPos = randomSelect(this._bossSlots);
      this._boss.setBossSlot(targetPos);
    }
    const tntCount = this._tntSlots.filter(pos => {
      const data = tileLayer.getData(pos);
      if (data) {
        return data.tile == TNT_TILE_ID;
      }
      return false;
    }).length;
    if (tntCount == 0) {
      const pos = randomSelect(this._tntSlots);
      tileLayer.setData(pos, new TileLayerData(TNT_TILE_ID, 0, false));
      setTileCollisionData(pos, 1);
      tileLayer.redraw();
    }
  }

  destroy() {}
}

function saveProgress(pos) {
  let hasDragon = currentLevel >= 1 && dragon && dragon.hasTarget(); 
  // A position hack to avoid record dragon before it triggered.
  if (currentLevel == 1 && pos.x < 205) {
    hasDragon = undefined;
  }
  const data = {
    level: currentLevel,
    unicorn: pos.add(vec2(0, 0.5)),
    dragon: hasDragon ? dragon.pos : undefined,
  };
  writeSaveData(`${STORAGE_PREFIX}save`, data);
}

function loadProgress() {
  const data = readSaveData(`${STORAGE_PREFIX}save`, undefined);
  if (!data || !data.unicorn) {
    return;
  }
  if (data.level != currentLevel) {
    return;
  }
  if (player) {
    player.pos = vec2(data.unicorn.x, data.unicorn.y);
  }
  if (data.dragon && dragon) {
    dragon.pos = vec2(data.dragon.x, data.dragon.y);
    dragon.setTargetObject(player);
  }
}
