function getShuffledRainbowColors(count) {
  const colors = [];
  while (colors.length < count) {
    const batch = RAINBOW_COLORS.map(color => color);
    for (let i = batch.length - 1; i > 0; --i) {
      const j = randInt(i + 1);
      [batch[i], batch[j]] = [batch[j], batch[i]];
    }
    colors.push(...batch);
  }
  return colors.slice(0, count);
}

function decodeTiledTile(gid) {
  const rawGid = gid >>> 0;
  const horizontal = !!(rawGid & TILED_FLIPPED_HORIZONTALLY_FLAG);
  const vertical = !!(rawGid & TILED_FLIPPED_VERTICALLY_FLAG);
  const diagonal = !!(rawGid & TILED_FLIPPED_DIAGONALLY_FLAG);
  const tile = (rawGid & TILED_TILE_ID_MASK) - 1;
  let direction = 0;
  let mirror = false;
  if (diagonal) {
    if (horizontal && vertical) {
      direction = 1;
      mirror = true;
    } else if (horizontal) {
      direction = 1;
    } else if (vertical) {
      direction = 3;
    } else {
      direction = 3;
      mirror = true;
    }
  } else if (horizontal && vertical) {
    direction = 2;
  } else if (horizontal) {
    mirror = true;
  } else if (vertical) {
    direction = 2;
    mirror = true;
  }
  return new TileLayerData(tile, direction, mirror);
}

